def load_instance(instance_idx: int, instances_path: Path = INSTANCES_PATH) -> dict[str, Any]:
    """
    Load a single inventory instance from ``parameters/instances.pkl``.

    Parameters
    ----------
    instance_idx : int
        Index into the pickled instance list.
    instances_path : Path
        Path to the pickle generated by ``parameters/param_generator.py``.

    Returns
    -------
    dict[str, Any]
        Environment kwargs for ``inventorygyms/TwoEchelonPLSTS-v0``.

    Raises
    ------
    FileNotFoundError
        If the instance pickle does not exist.
    TypeError
        If the pickle is not a list of dictionaries.
    ValueError
        If ``instance_idx`` is outside the available range.
    """
    if not instances_path.exists():
        raise FileNotFoundError(
            f"Could not find {instances_path}. Generate it with parameters/param_generator.py first."
        )

    with instances_path.open("rb") as file:
        instances = pickle.load(file)

    if not isinstance(instances, list) or not all(isinstance(item, dict) for item in instances):
        raise TypeError(f"Expected {instances_path} to contain a list[dict].")

    if instance_idx < 0 or instance_idx >= len(instances):
        raise ValueError(f"Instance index {instance_idx} out of range [0, {len(instances) - 1}]")

    return instances[instance_idx]


def demand_totals(instance_params: dict[str, Any]) -> tuple[float, float, float]:
    """
    Calculate total expected store, online, and combined demand for an instance.

    Parameters
    ----------
    instance_params : dict[str, Any]
        Instance dictionary loaded from ``parameters/instances.pkl``.

    Returns
    -------
    tuple[float, float, float]
        Store demand total, online demand total, and combined total demand.

    Raises
    ------
    ValueError
        If required demand parameters are missing or total demand is not positive.
    """
    store_demand_params = instance_params.get("store_demand_params")
    online_demand_params = instance_params.get("online_demand_params")
    if store_demand_params is None or online_demand_params is None:
        raise ValueError(
            "Instance must contain store_demand_params and online_demand_params to infer "
            "warehouse bounds."
        )

    store_demand = float(np.sum(np.asarray(store_demand_params, dtype=float)))
    online_demand = float(np.sum(np.asarray(online_demand_params, dtype=float)))
    total_demand = store_demand + online_demand

    if total_demand <= 0:
        raise ValueError("Total store and online demand must be positive to infer warehouse bounds.")

    return store_demand, online_demand, total_demand


def infer_min_wh(
    instance_params: dict[str, Any],
    online_demand_factor: float = MIN_WH_ONLINE_DEMAND_FACTOR,
) -> int:
    """
    Infer the minimum warehouse order-up-to level from total expected online demand.

    Parameters
    ----------
    instance_params : dict[str, Any]
        Instance dictionary loaded from ``parameters/instances.pkl``.
    online_demand_factor : float
        Multiplier applied to total expected online demand. Values below 1 make the
        lower bound a bit less than total expected online demand.

    Returns
    -------
    int
        Minimum warehouse order-up-to level.

    Raises
    ------
    ValueError
        If ``online_demand_factor`` is outside ``(0, 1]``.
    """
    if online_demand_factor <= 0 or online_demand_factor > 1:
        raise ValueError("online_demand_factor must be in the interval (0, 1].")

    _, online_demand, _ = demand_totals(instance_params)
    return int(np.floor(online_demand * online_demand_factor))


def infer_max_wh(instance_params: dict[str, Any], demand_factor: float = MAX_WH_DEMAND_FACTOR) -> int:
    """
    Infer a warehouse order-up-to search ceiling from total expected demand.

    ``parameters/param_generator.py`` stores ``store_demand_params`` as one demand-rate
    trajectory per store and ``online_demand_params`` as one demand rate per period.
    The inferred ceiling is deliberately above total expected store + online demand,
    but bounded to a simple demand multiple so Optuna does not search implausibly huge values.

    Parameters
    ----------
    instance_params : dict[str, Any]
        Instance dictionary loaded from ``parameters/instances.pkl``.
    demand_factor : float
        Multiplier applied to total expected demand. Must be greater than 1.

    Returns
    -------
    int
        Inferred maximum warehouse order-up-to level.

    Raises
    ------
    ValueError
        If demand parameters are missing or ``demand_factor`` is not greater than 1.
    """
    if demand_factor <= 1:
        raise ValueError("demand_factor must be greater than 1.")

    _, _, total_demand = demand_totals(instance_params)
    return int(np.ceil(total_demand * demand_factor))


def instance_summary(
    instance_idx: int,
    instance_params: dict[str, Any],
    min_wh: int,
    max_wh: int,
) -> dict[str, Any]:
    """
    Build metadata describing the instance and chosen warehouse search bound.

    Parameters
    ----------
    instance_idx : int
        Index of the selected instance in ``parameters/instances.pkl``.
    instance_params : dict[str, Any]
        Selected instance configuration.
    min_wh : int
        Minimum warehouse order-up-to level used by Optuna.
    max_wh : int
        Maximum warehouse order-up-to level used by Optuna.

    Returns
    -------
    dict[str, Any]
        Flat metadata suitable for adding to a CSV of trial results.
    """
    store_demand, online_demand, total_demand = demand_totals(instance_params)

    return {
        "instance_idx": instance_idx,
        "trajectory": instance_params.get("trajectory", instance_params.get("trajectory\"")),
        "stores": instance_params.get("stores"),
        "periods": instance_params.get("periods"),
        "cluster_method": instance_params.get("cluster_method"),
        "dfw_chance": instance_params.get("dfw_chance"),
        "holding_warehouse": instance_params.get("holding_warehouse"),
        "holding_store": instance_params.get("holding_store"),
        "penalty": instance_params.get("penalty"),
        "store_demand_total": store_demand,
        "online_demand_total": online_demand,
        "total_demand": total_demand,
        "min_wh": min_wh,
        "max_wh": max_wh,
    }


def build_output_path(output_dir: Path, study_name: str, instance_idx: int) -> Path:
    """
    Build a deterministic CSV path for a study result.

    Parameters
    ----------
    output_dir : Path
        Directory where the CSV should be written.
    study_name : str
        Optuna study name.
    instance_idx : int
        Selected instance index.

    Returns
    -------
    Path
        CSV output path.
    """
    safe_study_name = re.sub(r"[^A-Za-z0-9_.-]+", "_", study_name).strip("_")
    return output_dir / f"instance_{instance_idx}_{safe_study_name}.csv"


