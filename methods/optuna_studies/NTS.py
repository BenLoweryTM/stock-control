"""
Optuna study for the No Transhipment heuristic (NTS).

Warehouse inventory follows a regular base-stock policy; the order-up-to level
is the tuned parameter.

Store inventory follows a base-stock policy where each store's order-up-to level
is the inverse CDF of lead-time demand (LTD) evaluated at a shared Critical
Fractile CF:

    S_i = F_i^{-1}(CF),   F_i ~ Poisson(sum of store_demand_params[i] over store lead time)

CF ∈ (0, 1) is the same across all stores and is the second tuned parameter.

Usage
-----------------
    uv run ./methods/optuna_studies/NTS.py --jobs 8 --trials 100 --instance-idx 0
    uv run ./methods/optuna_studies/NTS.py --jobs 8 --trials 100 --instance-idx 0 --max-wh 1000
"""

from __future__ import annotations

import argparse
import pickle
import re
from multiprocessing import cpu_count
from pathlib import Path
from typing import Any

import gymnasium as gym
import inventorygyms  # noqa: F401
import inventorygyms.wrappers.transhipment.ESR_rust as ESR
import numpy as np
import optuna
import pandas as pd
import scipy.stats as sp
from joblib import Parallel, delayed

# Number of Monte-Carlo replications per Optuna trial
N_SIMS = 5000

STUDY_NAME = "inventory_tuning"
PROJECT_ROOT = Path(__file__).resolve().parents[2]
INSTANCES_PATH = PROJECT_ROOT / "parameters" / "instances.pkl"
RESULTS_DIR = PROJECT_ROOT / "results" / "NTS"
MIN_WH_ONLINE_DEMAND_FACTOR = 0.90
MAX_WH_DEMAND_FACTOR = 2.0


