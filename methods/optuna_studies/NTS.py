def build_output_path(output_dir: Path, study_name: str, instance_idx: int) -> Path:
    """
    Build a deterministic CSV path for a study result.

    Parameters
    ----------
    output_dir : Path
        Directory where the CSV should be written.
    study_name : str
        Optuna study name.
    instance_idx : int
        Selected instance index.

    Returns
    -------
    Path
        CSV output path.
    """
    safe_study_name = re.sub(r"[^A-Za-z0-9_.-]+", "_", study_name).strip("_")
    return output_dir / f"instance_{instance_idx}_{safe_study_name}.csv"


